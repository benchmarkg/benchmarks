#!/usr/bin/env python3
"""The maintainer rerun-policy audit (P8-S2-T04; 13-execution-runners.md S5.4, 05 S5).

    python scripts/check_rerun_policy.py --gate-passing             # the gate's passing set; non-zero on a breach
    python scripts/check_rerun_policy.py --all                      # every curated benchmark, for the record
    python scripts/check_rerun_policy.py --gate-passing --write docs/execution/rerun-policy-audit.md
    python scripts/check_rerun_policy.py --gate-passing --check docs/execution/rerun-policy-audit.md
    python scripts/check_rerun_policy.py --gate-passing --mode hidden-only      # ADR-0023's other option

13 S5.4 rule 1: "We never execute a benchmark whose maintainer has asked that items not be sent to third-party
endpoints, and contact-first blocks the run until there is a recorded answer." The policy is a curation field,
execution.maintainer_rerun_policy, so this script only joins and refuses; it never decides a policy.

The join (step 1). The set is scripts/runnable_gate.py's: the benchmarks passing all five of 13 S3's clauses over
the curated corpus (--gate-passing), or every curated benchmark (--all). Each is joined to its policy:

    unrestricted               runnable as far as this rule goes
    no-third-party-endpoints   a breach (step 2): we never run those, so it may not sit in the run set
    contact-first              a breach (step 3) unless docs/execution/maintainer-correspondence.md records a yes
    unstated                   listed (step 4); and what it defaults to is ADR-0023's (P8-S2-T06), the --mode:
                               block        a breach: a curator has not read the terms (the default, as
                                            ADR-0023 proposes; 13 S5.4 rule 4, "unstated is not permission")
                               hidden-only  a breach only where the record shows a withheld component --
                                            data.access train-open-test-held-out or private-test-server, or
                                            ground_truth_source held-out-labels -- rule 4's floor and no more

The recorded answer. P8-S2-T05, a person's correspondence, writes docs/execution/maintainer-correspondence.md. This
script reads one table from it, a row per benchmark, and nothing else in the file:

    | benchmark | answer | date | responder |
    | --- | --- | --- | --- |
    | swe-bench-verified | yes | 2027-03-02 | Jane Maintainer (SWE-bench) |

`answer` is `yes` or `no`; a yes with no date or no responder is not a recorded answer, and a `no` is recorded but
blocks the run as surely as silence. A file that does not exist records nothing.

Exit codes: 0 when the set holds no breach; 1 when it holds one (every breach is printed); 2 on a usage error or a
--check whose document no longer reproduces.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from dataclasses import dataclass, field

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, 'scripts'))

import runnable_gate  # noqa: E402

ANSWERS = os.path.join(ROOT, 'docs', 'execution', 'maintainer-correspondence.md')
POLICIES = ('unrestricted', 'no-third-party-endpoints', 'contact-first', 'unstated')
MODES = ('block', 'hidden-only')        # ADR-0023's two options; block is the one it proposes
WITHHELD_ACCESS = ('train-open-test-held-out', 'private-test-server')
ROW = re.compile(r'^\|\s*([a-z0-9][a-z0-9-]*)\s*\|\s*(yes|no)\s*\|\s*(\d{4}-\d{2}-\d{2})?\s*\|\s*([^|]*?)\s*\|\s*$', re.I)
BEGIN = '<!-- rerun-policy-audit:begin -- generated by scripts/check_rerun_policy.py --write; --check reproduces it -->'
END = '<!-- rerun-policy-audit:end -->'


@dataclass
class Answer:
    benchmark: str
    answer: str          # yes | no
    date: str | None
    responder: str

    @property
    def recorded(self) -> bool:
        return bool(self.date and self.responder)


@dataclass
class Audit:
    scope: str
    by_policy: dict[str, list[str]]
    breaches: list[str] = field(default_factory=list)
    mode: str = 'block'

    @property
    def unstated(self) -> list[str]:
        return self.by_policy['unstated']


def answers(path: str = ANSWERS) -> dict[str, Answer]:
    """The recorded answers in the correspondence table; {} when the file does not exist yet."""
    if not os.path.exists(path):
        return {}
    with open(path, encoding='utf-8') as f:
        return parse_answers(f.read())


def parse_answers(text: str) -> dict[str, Answer]:
    out = {}
    for line in text.splitlines():
        m = ROW.match(line)
        if m:
            out[m.group(1)] = Answer(m.group(1), m.group(2).lower(), m.group(3), m.group(4))
    return out


def answers_at(root: str, commit: str) -> dict[str, Answer]:
    """The correspondence table as it was at `commit`; {} when the file did not exist there."""
    import subprocess
    top = runnable_gate._git(root, 'rev-parse', '--show-toplevel')
    rel = os.path.relpath(os.path.join(os.path.abspath(root), 'docs', 'execution', 'maintainer-correspondence.md'),
                          top).replace(os.sep, '/')
    r = subprocess.run(['git', '-C', top, 'show', '%s:%s' % (commit, rel)], capture_output=True)
    return parse_answers(r.stdout.decode('utf-8')) if r.returncode == 0 else {}


def policy_of(record: dict) -> str:
    """The record's policy; the schema defaults it to unstated (04, P0-S4-T01), and so does a record with none."""
    ex = record.get('execution') if isinstance(record, dict) else None   # get-default: a record may hold no block
    p = ex.get('maintainer_rerun_policy') if isinstance(ex, dict) else None   # get-default: the schema default
    if p is None:
        return 'unstated'
    if p not in POLICIES:
        raise ValueError('%s: maintainer_rerun_policy %r is not one of %s' % (record['id'], p, ', '.join(POLICIES)))
    return p


def withheld(record: dict) -> str | None:
    """What shows a withheld component in a record, or None. data.access_by_phase is free text, so it is not read."""
    data = record.get('data') if isinstance(record.get('data'), dict) else {}     # get-default: a record may hold no data block
    if data.get('access') in WITHHELD_ACCESS:
        return 'data.access %s' % data['access']
    if record.get('ground_truth_source') == 'held-out-labels':
        return 'ground_truth_source held-out-labels'
    return None


def audit(records: dict[str, dict], ids: list[str], recorded: dict[str, Answer], scope: str,
          mode: str = 'block') -> Audit:
    if mode not in MODES:
        raise ValueError('mode %r is not one of %s' % (mode, ', '.join(MODES)))
    by = {p: [] for p in POLICIES}
    for rid in sorted(ids):
        by[policy_of(records[rid])].append(rid)
    a = Audit(scope, by, mode=mode)
    for rid in by['unstated']:
        shows = withheld(records[rid])
        if mode == 'block':
            a.breaches.append('%s is unstated: no curator has read its terms for this field, and under ADR-0023 '
                              'unstated blocks the run (13 S5.4 rule 4)%s' % (rid, ' -- and it shows %s' % shows
                                                                              if shows else ''))
        elif shows:
            a.breaches.append('%s is unstated and shows %s: a withheld component is never run on an unstated '
                              'policy (13 S5.4 rule 4)' % (rid, shows))
    for rid in by['no-third-party-endpoints']:
        a.breaches.append('%s is no-third-party-endpoints: its maintainer asked that items not be sent to third-party '
                          'endpoints, and we never run those (13 S5.4 rule 1)' % rid)
    for rid in by['contact-first']:
        ans = recorded.get(rid)                          # get-default: no row is no recorded answer
        if ans is None or not ans.recorded:
            a.breaches.append('%s is contact-first with no recorded answer (13 S5.4 rule 1): write to its maintainer '
                              'and record the reply in docs/execution/maintainer-correspondence.md (P8-S2-T05)' % rid)
        elif ans.answer != 'yes':
            a.breaches.append('%s is contact-first and its maintainer said no on %s (%s): drop it from the run set'
                              % (rid, ans.date, ans.responder))
    return a


def block(a: Audit, gate_count: int, total: int, commit: str | None) -> str:
    lines = [BEGIN, '', '### The join', '',
             'Scope: **%s** -- %d of %d curated benchmark record(s).' % (a.scope, sum(map(len, a.by_policy.values())),
                                                                       total),
             'Mode: **%s** (ADR-0023: what `unstated` defaults to).' % a.mode]
    if commit:
        lines.append('Counted over `data/benchmarks/` at commit `%s`.' % commit)
    lines += ['', '| maintainer_rerun_policy | benchmarks | |', '| --- | --- | --- |']
    note = {'unrestricted': 'runnable as far as this rule goes', 'no-third-party-endpoints': 'never run (rule 1)',
            'contact-first': 'blocked until a recorded yes (rule 1)',
            'unstated': 'blocked (ADR-0023, mode block)' if a.mode == 'block' else 'blocked where a component is withheld'}
    for p in POLICIES:
        ids = a.by_policy[p]
        lines.append('| %s | %d | %s%s |' % (p, len(ids), note[p], (': ' + ', '.join('`%s`' % i for i in ids)) if ids and
                                                                   p != 'unstated' else ''))
    lines += ['', '### Breaches', '']
    lines += ['- ' + b for b in a.breaches] or ['None.']
    lines += ['', '### Unstated (ADR-0023)', '']
    lines += ['- `%s`' % i for i in a.unstated] or ['None.']
    lines += ['', END]
    return '\n'.join(lines) + '\n'


def scope_ids(records: dict[str, dict], gate_passing: bool) -> tuple[list[str], str]:
    if gate_passing:
        return runnable_gate.run(records).passing, 'the runnable gate\'s passing set (scripts/runnable_gate.py, 13 S3)'
    return sorted(records), 'every curated benchmark'


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument('--gate-passing', action='store_true')
    g.add_argument('--all', action='store_true')
    p.add_argument('--root', default=ROOT)
    p.add_argument('--answers', default=None)
    p.add_argument('--mode', choices=MODES, default='block', help="what unstated defaults to (ADR-0023); default block")
    out = p.add_mutually_exclusive_group()
    out.add_argument('--write', metavar='PATH')
    out.add_argument('--check', metavar='PATH')
    a = p.parse_args(argv)
    commit = None
    if a.check:
        # --check recounts from the commit the document names, as scripts/runnable_gate.py --check does, so the
        # document keeps reproducing while the corpus moves on
        have = open(a.check, encoding='utf-8').read() if os.path.exists(a.check) else ''
        m = re.search(r'Counted over `data/benchmarks/` at commit `([0-9a-f]{40})`', have)
        if not m:
            print('%s names no corpus commit to recount from' % a.check)
            return 2
        commit = m.group(1)
        records, recorded = runnable_gate.load_at(a.root, commit), answers_at(a.root, commit)
    else:
        records = runnable_gate.load(a.root)
        recorded = answers(a.answers or os.path.join(a.root, 'docs', 'execution', 'maintainer-correspondence.md'))
    ids, scope = scope_ids(records, a.gate_passing)
    result = audit(records, ids, recorded, scope, a.mode)
    gate_count = len(runnable_gate.run(records).passing)
    if a.write or a.check:
        commit = commit or runnable_gate.corpus_commit(a.root)
        text = block(result, gate_count, len(records), commit)
        path = a.write or a.check
        if a.write:
            existing = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
            if BEGIN in existing and END in existing:
                new = existing[:existing.index(BEGIN)] + text + existing[existing.index(END) + len(END) + 1:]
            else:
                new = existing + ('\n' if existing and not existing.endswith('\n') else '') + text
            os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(new)
        else:
            have = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
            if BEGIN not in have or END not in have:
                print('%s holds no generated block' % path)
                return 2
            got = have[have.index(BEGIN):have.index(END) + len(END)] + '\n'
            if got != text:
                print('%s no longer reproduces: re-run with --write' % path)
                return 2
    for p_ in POLICIES:
        print('%-26s %d' % (p_, len(result.by_policy[p_])))
    print('scope: %s; %d record(s); mode %s' % (scope, len(ids), a.mode))
    for b in result.breaches:
        print('BREACH  ' + b)
    if result.breaches:
        return 1
    print('no breach: no gate-passing benchmark is no-third-party-endpoints, contact-first without a recorded yes, '
          'or unstated where mode %s blocks it' % a.mode if a.gate_passing else 'no breach')
    return 0


if __name__ == '__main__':
    sys.exit(main())
