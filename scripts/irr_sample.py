#!/usr/bin/env python3
"""Draw the 30-item inter-rater reliability sample and write the blind instrument (P1-S14-T01; 03 S6.1).

03 S6.1: "Draw 30 benchmarks from the stress corpus, stratified so every domain family present in that corpus
appears at least once -- that is 18 of the 19 families, engineering-design having no surveyed candidates --
and at least 6 of the 10 stress-tests are included." Two raters then classify each item "independently, from
primary sources, with no discussion, using only the published definitions".

The draw, from taxonomy/_corpus/stress-corpus.yaml with a fixed seed, so it reproduces:

  1. six of the ten stress tests (`stress_test: true`), chosen at random;
  2. for every family the corpus covers that those six leave out, one item of that family, chosen at random
     from its items that are not stress tests;
  3. items that are not stress tests, chosen at random, until there are 30.

Exactly six stress tests, so the sample meets the floor without leaning on chance. The instrument,
taxonomy/_irr/sample.yaml, is blind:

  items        the 30 items in a random order, each with its id, its name and its primary-source links (the
               corpus's `url`, the primary paper's url and arXiv id or DOI, or the organiser's
               `primary_source`) and nothing else: no family, no stress-test flag, no description, no tag.
               A `url` that is a repository under a person's own account is left out (PERSONAL_HOME).
  vocabularies the options for each rated facet in a random order, each with the published `label`,
               `definition`, `inclusion_test` and `exclusion_test`. Not the terms' `examples`: those name
               catalogued benchmarks with their tags, and a sampled item could be one of them. Retired and
               deprecated terms are left out, and so is a value the build derives rather than a curator
               tags (`lifecycle: saturated`).
  facets       the facets 03 S6.2 rates, single-valued or multi-valued, and the vocabulary each draws on.
               Capability groups are not rated (03 S6.2: "derived, never hand-tagged").

    python scripts/irr_sample.py                 # write taxonomy/_irr/sample.yaml
    python scripts/irr_sample.py --check         # exit 1 if it differs from a fresh draw or breaks a rule
    python scripts/irr_sample.py --check --sample PATH      # check another copy (the tests do)

--check asserts the four properties directly on the file (30 items; every corpus family present; at least
six stress tests; no stored tag on an item) before comparing it with a fresh draw.
"""
from __future__ import annotations

import argparse
import os
import random
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORPUS = 'taxonomy/_corpus/stress-corpus.yaml'
SAMPLE = 'taxonomy/_irr/sample.yaml'
SEED = 20261117
SIZE = 30
STRESS_MIN = 6
ITEM_KEYS = {'id', 'name', 'links'}
LINK_KEYS = {'kind', 'url', 'arxiv_id', 'doi'}
OPTION_KEYS = ('id', 'label', 'definition', 'inclusion_test', 'exclusion_test')
LIVE = ('proposed', 'active')
DERIVED = {('lifecycle', 'saturated')}                    # lifecycle.yaml marks it derived: true
# Items whose corpus `url` is a repository under a person's own account: the instrument ships the paper instead.
PERSONAL_HOME = {'gpqa-diamond'}

# 03 S6.2's facets: (facet, single or multi, vocabulary file, the `field` its terms carry, or None).
FACETS = [
    ('domain.primary', 'single', 'domains.yaml', None),
    ('domain.secondary', 'multi', 'domains.yaml', None),
    ('capability', 'multi', 'capabilities.yaml', None),
    ('evaluation_method', 'multi', 'evaluation-methods.yaml', None),
    ('designed_for_subjects', 'multi', 'subjects.yaml', None),
    ('lifecycle', 'single', 'lifecycle.yaml', 'lifecycle'),
    ('data.access', 'single', 'data-properties.yaml', 'data.access'),
    ('data.refresh', 'single', 'data-properties.yaml', 'data.refresh'),
    ('data.contamination_risk', 'single', 'data-properties.yaml', 'data.contamination_risk'),
    ('data.ceiling_anchor_type', 'single', 'ceiling-anchors.yaml', 'data.ceiling_anchor_type'),
    ('execution.reproducibility_tier', 'single', 'execution.yaml', 'execution.reproducibility_tier'),
    ('governance.independence_flags', 'multi', 'governance.yaml', 'governance.independence_flags'),
]

HEADER = """\
# taxonomy/_irr/sample.yaml -- the blind inter-rater reliability instrument (P1-S14-T01; 03 S6.1, S6.2)
#
# GENERATED by scripts/irr_sample.py from taxonomy/_corpus/stress-corpus.yaml and the vocabularies, with a
# fixed seed; `python scripts/irr_sample.py --check` fails if it drifts. Do not edit by hand.
#
# For each item, classify every facet below from the item's primary sources alone, using only the
# definitions and tests in `vocabularies`: one value for a single-valued facet, any number for a
# multi-valued one. Work independently: no discussion with the other rater, and no look at the catalogue's
# entries, the stress corpus or its classifications, which carry the stored values this instrument hides.
# The domain options are subdomains: a primary domain is a subdomain, not a family (02 S3).

"""


def load(path):
    with open(path, encoding='utf-8') as fh:
        return yaml.safe_load(fh)


def corpus(root):
    return load(os.path.join(root, *CORPUS.split('/')))['entries']


def draw(items, seed=SEED):
    """The 30 sampled corpus items, in instrument order."""
    rng = random.Random(seed)
    stress = sorted((x for x in items if x.get('stress_test') is True), key=lambda x: x['id'])
    rest = sorted((x for x in items if x.get('stress_test') is not True), key=lambda x: x['id'])
    chosen = rng.sample(stress, STRESS_MIN)
    for fam in sorted({x['domain_family'] for x in items}):
        if not any(x['domain_family'] == fam for x in chosen):
            chosen.append(rng.choice([x for x in rest if x['domain_family'] == fam]))
    pool = [x for x in rest if x not in chosen]
    rng.shuffle(pool)
    chosen += pool[:SIZE - len(chosen)]
    rng.shuffle(chosen)
    return chosen, rng


def links(x):
    out = [] if x['id'] in PERSONAL_HOME else [{'kind': 'home', 'url': x['url']}]
    paper = x.get('primary_paper') or {}
    if paper:
        out.append({k: v for k, v in (('kind', 'paper'), ('url', paper.get('url')), ('arxiv_id', paper.get('arxiv_id')),
                                      ('doi', paper.get('doi'))) if v})
    src = x.get('primary_source')
    if isinstance(src, dict) and src.get('url'):
        out.append({'kind': 'primary-source', 'url': src['url']})
    elif isinstance(src, str):
        out.append({'kind': 'primary-source', 'url': src})
    return out


def vocabularies(root, rng):
    out = {}
    for facet, _, fname, field in FACETS:
        key = fname[:-5] if field is None else field
        if key in out:
            continue
        terms = load(os.path.join(root, 'taxonomy', fname))['terms']
        opts = [t for t in terms if t.get('status') in LIVE and t.get('field') == field
                and (fname != 'domains.yaml' or t.get('parent'))
                and (facet, t['id']) not in DERIVED and not t.get('derived')]
        opts = [{k: ' '.join(str(t[k]).split()) for k in OPTION_KEYS if t.get(k)} for t in opts]
        rng.shuffle(opts)
        out[key] = opts
    return out


def build(root=ROOT):
    items = corpus(root)
    chosen, rng = draw(items)
    with open(os.path.join(root, 'taxonomy', 'VERSION'), encoding='utf-8') as fh:
        version = fh.read().strip()
    vocab = vocabularies(root, rng)
    return {
        'version': 1,
        'seed': SEED,
        'corpus': CORPUS,
        'corpus_version': load(os.path.join(root, *CORPUS.split('/')))['version'],
        'taxonomy_version': version,
        'draw': '%d items: %d of the %d stress tests, one item for each corpus family they leave out, the rest '
                'at random from the items that are not stress tests' % (
                    SIZE, STRESS_MIN, sum(1 for x in items if x.get('stress_test') is True)),
        'facets': [{'facet': f, 'kind': k, 'vocabulary': fn[:-5] if fld is None else fld} for f, k, fn, fld in FACETS],
        'items': [{'id': x['id'], 'name': x['name'], 'links': links(x)} for x in chosen],
        'vocabularies': vocab,
    }


def render(doc):
    return HEADER + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=110, default_flow_style=False)


def properties(sample, items):
    """The four done_when properties of P1-S14-T01, read off the instrument itself."""
    errs = []
    rows = sample.get('items') if isinstance(sample, dict) else None
    if not isinstance(rows, list):
        return ['the sample has no `items` list']
    by_id = {x['id']: x for x in items}
    if len(rows) != SIZE:
        errs.append('%d items, not %d' % (len(rows), SIZE))
    ids = [r.get('id') for r in rows if isinstance(r, dict)]
    if len(set(ids)) != len(ids):
        errs.append('an item is listed twice')
    unknown = [i for i in ids if i not in by_id]
    if unknown:
        errs.append('items not in the stress corpus: %s' % ', '.join(map(str, unknown)))
    want = {x['domain_family'] for x in items}
    have = {by_id[i]['domain_family'] for i in ids if i in by_id}
    if want - have:
        errs.append('corpus families missing from the sample: %s' % ', '.join(sorted(want - have)))
    stress = sum(1 for i in ids if i in by_id and by_id[i].get('stress_test') is True)
    if stress < STRESS_MIN:
        errs.append('%d stress tests, fewer than %d' % (stress, STRESS_MIN))
    for r in rows:
        if not isinstance(r, dict):
            errs.append('an item is not a mapping')
            continue
        extra = set(r) - ITEM_KEYS
        if extra:
            errs.append('item %s carries a stored tag or another key the instrument must not ship: %s'
                        % (r.get('id'), ', '.join(sorted(extra))))
        for link in r.get('links') or []:
            if not isinstance(link, dict) or set(link) - LINK_KEYS:
                errs.append('item %s has a link with keys beyond %s' % (r.get('id'), sorted(LINK_KEYS)))
    return errs


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--root', default=ROOT)
    ap.add_argument('--sample', default=None, help='default: <root>/%s' % SAMPLE)
    ap.add_argument('--check', action='store_true', help='exit 1 if the sample breaks a rule or drifts')
    a = ap.parse_args(argv)
    path = a.sample or os.path.join(a.root, *SAMPLE.split('/'))
    want = render(build(a.root))
    if not a.check:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(want)
        print('wrote %s' % os.path.relpath(path, a.root))
        return 0
    if not os.path.exists(path):
        print('FAIL  %s does not exist: run scripts/irr_sample.py' % path)
        return 1
    with open(path, encoding='utf-8') as fh:
        text = fh.read()
    errs = properties(yaml.safe_load(text), corpus(a.root))
    if text != want:
        errs.append('%s is not what scripts/irr_sample.py draws: regenerate it' % os.path.relpath(path, a.root))
    for e in errs:
        print('FAIL  ' + e)
    if errs:
        return 1
    doc = yaml.safe_load(text)
    print('OK    %d items, every corpus family present, %d stress tests, no stored tags; %s'
          % (len(doc['items']), STRESS_MIN, ', '.join('%s %d' % (k, len(v)) for k, v in doc['vocabularies'].items())))
    return 0


if __name__ == '__main__':
    sys.exit(main())
