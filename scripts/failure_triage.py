"""Triage the Stage-3 failure log (P1-S1-T06; 03 S3.3 and S8).

    python scripts/failure_triage.py            # write `route`/`adr` and the Stage 4 revision list
    python scripts/failure_triage.py --check    # exit 1 if either is out of date

Every failure in taxonomy/_failures/ is routed one of three ways (schema.classification.ROUTES):

  adr        an ADR decides it. The ADRs are the source: a failure is routed to the ADR whose
             `## Evidence` section names it, except under a heading that says the ADR does not
             cover it. A failure named by two ADRs is an error.
  homograph  a collision whose terms sit in different facet files (03 S3.3): it routes to
             taxonomy/homographs.yaml for a declaration, not to a rename.
  stage-4    everything else, batched into the Stage 4 revision (P1-S1-T07).

The Stage 4 revision list, taxonomy/_failures/stage-4-revision-list.md, is generated from the routed
records that are still open (no `resolved` block): grouped by field, then by the term a failure
proposes, or for the rest by kind (and, for a collision, by the terms it is between). Never edit it
by hand.
"""
from __future__ import annotations

import argparse
import collections
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from schema.taxonomy import read_yaml  # noqa: E402

FAILURES = 'taxonomy/_failures'
LIST = 'taxonomy/_failures/stage-4-revision-list.md'
CITED = re.compile(r'taxonomy/_failures/(\d{4}-\d{2}-\d{2}-[a-z0-9-]+-\d{3})\.yaml')
TRIAGE_KEYS = re.compile(r'^(route|adr):.*\n?', re.M)


def adr_map(root: str) -> dict[str, str]:
    """failure id -> adr path, from each ADR's Evidence section."""
    out: dict[str, str] = {}
    for path in sorted(glob.glob(os.path.join(root, 'adr', '[0-9][0-9][0-9][0-9]-*.md'))):
        rel = 'adr/' + os.path.basename(path)
        text = open(path, encoding='utf-8').read()
        if '\n## Evidence' not in text:
            continue
        covered = True
        for line in text.split('\n## Evidence', 1)[1].splitlines():
            if line.startswith('## '):
                break
            if line.strip() and not line.lstrip().startswith('- '):
                covered = 'not covered' not in line.lower()
                continue
            for fid in CITED.findall(line) if covered else ():
                if out.get(fid, rel) != rel:
                    raise SystemExit('%s is named by both %s and %s' % (fid, out[fid], rel))
                out[fid] = rel
    return out


def facet_files(root: str) -> dict[str, set[str]]:
    """term id -> the taxonomy files that define it."""
    out: dict[str, set[str]] = collections.defaultdict(set)
    for path in glob.glob(os.path.join(root, 'taxonomy', '*.yaml')):
        for t in (read_yaml(path) or {}).get('terms') or []:
            if isinstance(t, dict) and 'id' in t:
                out[t['id']].add(os.path.basename(path))
    return out


def load(root: str) -> dict[str, tuple[str, dict]]:
    return {os.path.basename(p)[:-5]: (p, read_yaml(p))
            for p in sorted(glob.glob(os.path.join(root, FAILURES, '*.yaml')))}


def route_of(fid: str, f: dict, adrs: dict[str, str], files: dict[str, set[str]]) -> tuple[str, str | None]:
    if fid in adrs:
        return 'adr', adrs[fid]
    if f.get('kind') == 'collision':
        homes = [frozenset(files.get(t, ())) for t in f.get('terms') or []]
        if len({h for h in homes if h}) > 1:
            return 'homograph', None
    return 'stage-4', None


def retriaged(text: str, route: str, adr: str | None) -> str:
    body = TRIAGE_KEYS.sub('', text).rstrip('\n') + '\n'
    return body + 'route: %s\n' % route + ('adr: %s\n' % adr if adr else '')


def render(records: dict[str, tuple[str, dict]], routes: dict[str, tuple[str, str | None]]) -> str:
    stage4 = {fid: f for fid, (_, f) in records.items() if routes[fid][0] == 'stage-4' and not f.get('resolved')}
    resolved = sum(1 for _, f in records.values() if f.get('resolved'))
    by_route = collections.Counter(r for r, _ in routes.values())
    adrs = collections.Counter(a for r, a in routes.values() if a)
    lines = [
        '# Stage 4 revision list',
        '',
        'Generated by `scripts/failure_triage.py` from taxonomy/_failures/ (P1-S1-T06). Do not edit by hand:',
        'change a failure record or an ADR and re-run the script.',
        '',
        'Of %d failure records, %d are decided by an ADR, %d route to homographs.yaml and %d were batched'
        % (len(routes), by_route['adr'], by_route['homograph'], by_route['stage-4']),
        'for the Stage 4 revision (P1-S1-T07). %d records are marked `resolved` (by a later re-run or a'
        % resolved,
        'ruling) and are left out below, so this list is what is still open: %d records. A record appears'
        % len(stage4),
        'once, under its field, then under the term it proposes, or else under its kind.',
        '',
        '| ADR | Failures it decides |',
        '| --- | --- |',
    ]
    lines += ['| [%s](../../%s) | %d |' % (a[4:-3], a, n) for a, n in sorted(adrs.items())]
    by_field = collections.defaultdict(list)
    for fid, f in stage4.items():
        by_field[f['facet']].append((fid, f))
    lines += ['', '| Field | Failures |', '| --- | --- |']
    order = sorted(by_field, key=lambda k: (-len(by_field[k]), k))
    lines += ['| `%s` | %d |' % (k, len(by_field[k])) for k in order]
    for field in order:
        groups = collections.defaultdict(list)
        for fid, f in by_field[field]:
            if f.get('proposed_term'):
                key = 'Proposed: `%s`' % f['proposed_term']
            elif f.get('terms'):
                key = '%s between %s' % (f['kind'], ', '.join('`%s`' % t for t in sorted(f['terms'])))
            else:
                key = f['kind']
            groups[key].append(fid)
        lines += ['', '## `%s` (%d)' % (field, len(by_field[field]))]
        for key in sorted(groups, key=lambda k: (-len(groups[k]), k)):
            lines += ['', '- %s (%d)' % (key, len(groups[key]))]
            lines += ['  - [%s](%s.yaml)' % (fid, fid) for fid in sorted(groups[key])]
    return '\n'.join(lines) + '\n'


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true', help='report what is out of date and exit 1; write nothing')
    ap.add_argument('--root', default=ROOT)
    args = ap.parse_args(argv)
    records = load(args.root)
    adrs = adr_map(args.root)
    unknown = sorted(set(adrs) - set(records))
    if unknown:
        print('ADRs name failures that do not exist: %s' % ', '.join(unknown))
        return 1
    files = facet_files(args.root)
    routes = {fid: route_of(fid, f, adrs, files) for fid, (_, f) in records.items()}
    stale = []
    for fid, (path, _) in records.items():
        text = open(path, encoding='utf-8').read()
        new = retriaged(text, *routes[fid])
        if new != text:
            stale.append(path)
            if not args.check:
                open(path, 'w', encoding='utf-8', newline='\n').write(new)
    listing = render(records, routes)
    list_path = os.path.join(args.root, LIST)
    old = open(list_path, encoding='utf-8').read() if os.path.exists(list_path) else None
    if old != listing:
        stale.append(list_path)
        if not args.check:
            open(list_path, 'w', encoding='utf-8', newline='\n').write(listing)
    counts = collections.Counter(r for r, _ in routes.values())
    print('failures: %d  adr: %d  homograph: %d  stage-4: %d  %s: %d'
          % (len(routes), counts['adr'], counts['homograph'], counts['stage-4'],
             'out of date' if args.check else 'written', len(stale)))
    return 1 if args.check and stale else 0


if __name__ == '__main__':
    sys.exit(main())
