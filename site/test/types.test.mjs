// site/test/types.test.mjs -- P2-S1-T03. The site reads its entities through the generated interfaces.
//
// Two properties, checked as source text (astro:content only exists inside an Astro build): every collection
// in content.config.ts is fed by the corpus artifact with no schema of its own, and the accessors in
// src/lib/collections.ts type each entry with an interface from src/types/, which `bench schema gen` writes.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const read = (p) => readFileSync(here(p), 'utf8');

const KINDS = [
  ['benchmarks', 'benchmark', 'Benchmark'],
  ['systems', 'system', 'System'],
  ['organizations', 'organization', 'Organization'],
  ['metrics', 'metric', 'Metric'],
  ['sources', 'source', 'Source'],
];

test('every collection is loaded from the corpus artifact', () => {
  const config = read('../src/content.config.ts');
  for (const [name, kind] of KINDS) {
    assert.ok(config.includes(`${name}: defineCollection({ loader: () => corpusEntities('${kind}') })`), name);
  }
});

test('the accessors type entries with the generated interfaces, not a schema of their own', () => {
  const lib = read('../src/lib/collections.ts');
  for (const [, file, name] of KINDS) {
    assert.ok(existsSync(here(`../src/types/${file}.d.ts`)), `src/types/${file}.d.ts is generated by bench schema gen`);
    assert.ok(lib.includes(`import type { ${name} } from '../types/${file}';`), name);
    assert.ok(lib.includes(`e.data as ${name})`), name);
  }
  const both = lib + read('../src/lib/corpus.ts');
  assert.ok(!both.includes("from 'zod'") && !both.includes("from 'astro/zod'"), 'no second schema');
});

test('the site has a strict tsconfig that includes its sources', () => {
  const cfg = JSON.parse(read('../tsconfig.json'));
  assert.equal(cfg.extends, 'astro/tsconfigs/strict');
  assert.ok(cfg.include.includes('src/**/*'));
});
